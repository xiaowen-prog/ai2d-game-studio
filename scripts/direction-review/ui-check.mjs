import { app, BrowserWindow } from 'electron';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';
const evidence = resolve(process.env.DIRECTION_EVIDENCE_DIR || '../开发工作区/projects/AI2D游戏制作平台/docs/evidence/阶段2-1');
app.setPath('userData', resolve('.noobi-private/direction-ui-check'));
void app.whenReady().then(async () => {
await mkdir(evidence, { recursive: true });
const win = new BrowserWindow({ width: 1280, height: 1000, show: false, webPreferences: { contextIsolation: true, nodeIntegration: false } });
const run = (code) => win.webContents.executeJavaScript(code);
const wait = async (code) => { for (let i = 0; i < 120; i++) { if (await run(code)) return; await new Promise((r) => setTimeout(r, 50)); } throw new Error(`UI condition timed out: ${code}`); };
const click = async (label) => { await wait(`Array.from(document.querySelectorAll('button')).some(b=>b.textContent.trim()===${JSON.stringify(label)}&&!b.disabled)`); await run(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()===${JSON.stringify(label)}).click()`); };
const fill = (id, value) => run(`(()=>{const e=document.getElementById(${JSON.stringify(id)});Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}));})()`);
const state = () => run(`fetch('/api/state').then(r=>r.json())`);
const results = [];
try {
  await win.loadURL('http://127.0.0.1:8794/');
  await wait(`!!document.getElementById('review-idea')`);
  await fill('review-idea', '我想做一个武侠类的 2D 俯视打怪游戏');
  await click('保存为新想法'); await click('开始方向');
  await wait(`!!document.querySelector('.creation-direction')`);
  assert.match(await run('document.body.innerText'), /预置示例，不调用 AI/);
  results.push('新想法 → 方向卡；明确显示离线示例');
  const first = await state();
  await fill('creation-request', '改成手动攻击，其他保持不变');
  await run(`document.getElementById('creation-request').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',isComposing:true,bubbles:true}))`);
  await run(`document.getElementById('creation-request').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',shiftKey:true,bubbles:true}))`);
  assert.equal((await state()).calls, first.calls);
  await run(`document.getElementById('creation-request').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))`);
  await wait(`document.querySelector('.creation-direction')?.textContent.includes('空格键手动攻击')`);
  results.push('中文组合输入和 Shift+Enter 不发送，Enter 提交修改');
  await click('确认方向并保存');
  await wait(`document.querySelector('.creation-status')?.textContent==='已确认'`);
  const confirmed = await state();
  assert.equal(confirmed.workflow.currentStage, 'direction');
  assert.equal(confirmed.workflow.steps.character.status, 'idle');
  assert.equal(confirmed.calls, first.calls + 1);
  await fill('creation-request', '衣服改成蓝色'); await click('发送修改');
  await wait(`!!document.querySelector('[role=dialog]')`); await click('先不改');
  assert.equal((await state()).calls, confirmed.calls);
  results.push('确认只保存方向；取消修改不发起生成');
  await run(`(()=>{const s=document.getElementById('creation-history');s.value=s.options[s.options.length-1].value;s.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await click('恢复这个版本'); await click('确认影响，继续');
  await wait(`document.querySelector('.creation-direction')?.textContent.includes('自动发射剑气')`);
  assert.equal((await state()).calls, confirmed.calls);
  assert.equal((await state()).workflow.steps.direction.confirmedVersionId, null);
  results.push('旧版方向和待确认状态一起恢复，不调用生成');
  await fill('creation-request', '明天继续修改这段草稿');
  await new Promise((r) => setTimeout(r, 350)); await win.webContents.reload();
  await wait(`document.getElementById('creation-request')?.value==='明天继续修改这段草稿'`);
  await click('确认方向并保存');
  await wait(`document.querySelector('.creation-status')?.textContent==='已确认'`);
  await win.webContents.reload();
  await wait(`document.querySelector('.creation-status')?.textContent==='已确认'`);
  assert.equal((await state()).calls, confirmed.calls);
  results.push('刷新后保留方向、确认和输入草稿，不重新生成');
  await writeFile(join(evidence, '方向卡-桌面-离线.png'), (await win.webContents.capturePage()).toPNG());
  win.setContentSize(390, 844);
  await new Promise((r) => setTimeout(r, 300));
  assert.equal(await run('document.documentElement.scrollWidth <= innerWidth'), true);
  assert.equal(await run(`getComputedStyle(document.querySelector('.creation-history')).display !== 'none'`), true);
  await writeFile(join(evidence, '方向卡-窄窗口-离线.png'), (await win.webContents.capturePage()).toPNG());
  results.push('390px 窄窗口无横向溢出，保留历史恢复入口');
  await writeFile(join(evidence, '界面检查.json'), JSON.stringify({ checkedAt: new Date().toISOString(), mode: 'offline fixture, real component and workflow store', realModelCalls: 0, results }, null, 2));
  console.log(`界面检查通过：${results.length} 组；真实模型调用 0 次。`);
  win.destroy(); app.exit(0);
} catch (error) {
  console.error(error.message); await writeFile(join(evidence, '方向卡-检查失败.png'), (await win.webContents.capturePage()).toPNG());
  win.destroy(); app.exit(1);
}

}).catch((error) => { console.error(error.message); app.exit(1); });
